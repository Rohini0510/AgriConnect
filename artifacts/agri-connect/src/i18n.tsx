interface LangContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TKey, vars?: Vars) => string;
  localize: (text: string) => string;
  localizeState: (state: string) => string;
  localizeCrop: (crop: string) => string;
  localizeStatus: (status: string) => string;
  localizeGrade: (grade: string) => string;
  localizeNode: (node: string) => string;
  localizeFpo: (name: string) => string;
  localizeName: (name: string) => string;
}

const LangContext = createContext<LangContextValue | null>(null);

function build(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      return saved === 'hi' || saved === 'mr' || saved === 'en' ? saved : 'en';
    } catch {
      return 'en';
    }
  });

  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
      document.documentElement.lang = locale;
    } catch {
      /* ignore storage errors */
    }
  }, [locale]);

  const localize = (text: string): string => {
    if (!text || locale === 'en') return text;
    const entry = entityMap[text];
    if (entry && entry[locale]) return entry[locale];
    return text;
  };

  const value: LangContextValue = {
    locale,
    setLocale: setLocaleState,
    t: (key, vars) => build(dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? String(key), vars),
    localize,
    localizeState: (state) => (locale === 'en' ? state : entityMap[state]?.[locale] ?? state),
    localizeCrop: (crop) => (locale === 'en' ? crop : entityMap[crop]?.[locale] ?? crop),
    localizeStatus: (status) => (locale === 'en' ? status : entityMap[status]?.[locale] ?? status),
    localizeGrade: (grade) => (locale === 'en' ? grade : entityMap[grade]?.[locale] ?? grade),
    localizeNode: (node) => (locale === 'en' ? node : entityMap[node]?.[locale] ?? node),
    localizeFpo: (name) => (locale === 'en' ? name : entityMap[name]?.[locale] ?? name),
    localizeName: (name) => (locale === 'en' ? name : entityMap[name]?.[locale] ?? name),
  };

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useLang(): LangContextValue {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error('useLang must be used within a LanguageProvider');
  return ctx;
}